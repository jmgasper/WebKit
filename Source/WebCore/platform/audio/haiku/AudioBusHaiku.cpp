#include "config.h"
#include "AudioBus.h"

#if ENABLE(WEB_AUDIO)

#include "AudioFileReader.h"

// Generated by PlatformHaiku.cmake from platform/audio/resources/Composite.wav:
// the HRTF impulse responses PannerNode uses, in the library rather than in
// files beside it.
#include "HaikuHRTFComposite.h"

namespace WebCore {

RefPtr<AudioBus> AudioBus::loadPlatformResource(StringView name, float sampleRate)
{
    // HRTFElevation asks for the concatenated responses only.
    if (name != "Composite"_s)
        return nullptr;
    return createBusFromInMemoryAudioFile(std::span<const uint8_t>(hrtfCompositeWav, sizeof(hrtfCompositeWav)), false, sampleRate);
}

} // namespace WebCore

#endif // ENABLE(WEB_AUDIO)
